import test from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import { createServer } from 'vite';
import { findBrowser } from './browser-path.mjs';

test('web Settings shows this browser, keeps export on the hub, edits hub settings and works at phone width', async t => {
  const executablePath = findBrowser();
  if (!executablePath) return t.skip('no chromium found');
  const server = await createServer({ configFile: fileURLToPath(new URL('../vite.config.ts', import.meta.url)), server: { host: '127.0.0.1', port: 0 } });
  t.after(() => server.close());
  await server.listen();
  const browser = await chromium.launch({ executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage'] });
  t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1280, height: 820 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${server.resolvedUrls.local[0]}test/web-settings.html`);
  await page.getByRole('button', { name: /^Settings/ }).first().click();
  const nav = name => page.locator('nav[aria-label="Settings sections"]').getByRole('button', { name, exact: true }).click();
  await page.getByText('This browser is Pixel browser').waitFor();
  assert.ok(await page.getByRole('button', { name: 'Forget browser' }).isVisible());
  await nav('Data and privacy');
  await page.getByText(/only work from the hub's own computer/).waitFor();
  assert.ok(await page.getByRole('button', { name: 'Export' }).isDisabled());
  await nav('About');
  await page.getByText('Commit abc1234').waitFor();
  await nav('Agents');
  const cap = page.getByLabel('Maximum agents at once');
  await cap.fill('5'); await cap.press('Enter');
  await page.getByRole('button', { name: 'Reset' }).first().waitFor();
  assert.deepEqual(await page.evaluate(() => window.calls.filter(c => c.method === 'settings.set').map(c => c.body)), [{ key: 'pool.cap', value: 5 }]);
  if (process.env.WEB_SETTINGS_SHOTS) await page.screenshot({ path: `${process.env.WEB_SETTINGS_SHOTS}/web-settings-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: /^Settings/ }).first().click();
  await page.getByRole('button', { name: 'Settings', exact: true }).first().click();
  await page.getByRole('button', { name: /Paired devices/ }).click();
  await page.getByText('Pixel browser', { exact: false }).first().waitFor();
  const width = await page.locator('h1').first().evaluate(el => el.getBoundingClientRect().width);
  assert.ok(width > 250, `settings content is ${width}px wide at phone width`);
  if (process.env.WEB_SETTINGS_SHOTS) await page.screenshot({ path: `${process.env.WEB_SETTINGS_SHOTS}/web-settings-phone.png` });
  assert.deepEqual(errors, []);
});
